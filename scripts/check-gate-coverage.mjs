#!/usr/bin/env node
/**
 * Fails `npm run verify` if any git-tracked source file escapes the lint or prettier gates.
 *
 * The npm-script globs are hand-maintained and have silently excluded real source three times:
 * all .jsx (T048), amplify override.ts (T046), and the Lambda sources, which were linted but
 * never prettier-checked. This takes `git ls-files` as the source of truth instead: eslint and
 * prettier run over the tracked list itself, so a new source file is covered the moment it is
 * tracked. Anything genuinely out of scope must be named in EXEMPT below, where it is visible.
 */

import { execFileSync } from 'node:child_process';

const SOURCE_EXTENSIONS = /\.(js|jsx|ts)$/;

/** Paths excluded on purpose. Each entry needs a reason — silence is what this script exists to stop. */
const EXEMPT = [
  { pattern: /^docs\/archive\//, reason: 'archived Codex/Copilot workflow, not maintained' },
  { pattern: /\.d\.ts$/, reason: 'generated by the Amplify CLI' },
  { pattern: /^[^/]+\.config\.(js|cjs|mjs)$/, reason: 'root tooling config, not app source' },
  { pattern: /^scripts\//, reason: 'build scripts run outside the app gates' },
];

/**
 * Lists git-tracked source files that the quality gates must cover.
 * @returns {string[]} Repo-relative paths.
 */
function listTrackedSourceFiles() {
  const tracked = execFileSync('git', ['ls-files'], { encoding: 'utf8' }).split('\n');

  return tracked
    .filter((file) => file && SOURCE_EXTENSIONS.test(file))
    .filter((file) => !EXEMPT.some(({ pattern }) => pattern.test(file)));
}

/**
 * Runs a gate command over the given files, letting its output through to the terminal.
 * @param {string} label - Gate name for the failure message.
 * @param {string[]} command - Command and leading arguments.
 * @param {string[]} files - Files to check.
 * @returns {boolean} True when the gate passed.
 */
function runGate(label, command, files) {
  const [bin, ...args] = command;

  try {
    execFileSync(bin, [...args, ...files], { stdio: 'inherit' });
    return true;
  } catch {
    process.stderr.write(`\ngate-coverage: ${label} failed on a tracked source file.\n`);
    return false;
  }
}

const files = listTrackedSourceFiles();

if (files.length === 0) {
  process.stderr.write('gate-coverage: no tracked source files found — check EXEMPT.\n');
  process.exit(1);
}

const results = [
  runGate('eslint', ['npx', 'eslint', '--max-warnings', '0'], files),
  runGate('prettier', ['npx', 'prettier', '--check'], files),
];

if (results.includes(false)) {
  process.exit(1);
}

process.stdout.write(`gate-coverage: ${files.length} tracked source files linted and formatted.\n`);
